/**
 * Writes VOCABULARY_REPORT.md: what the sign vocabulary contains, where each sign comes
 * from, how it was cross-verified against ASL-LEX 2.0, how well it covers everyday
 * words, and what is still approximate. `npm run seed:report -w server`.
 * Every number about the current data is computed from the shipped seed.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import * as data from './seedData.js';
import { crossVerify, validateSeed } from './validateSeed.js';
import { loadAslLexRows } from './seedData/aslLex/index.js';
import { CORE_VOCABULARY } from './seedData/coreVocabulary.js';
import { GRAMMAR_WORDS } from './seedData/wordLists.js';

const here = path.dirname(fileURLToPath(import.meta.url));

export function coverage(gestures = data.gestures) {
  const byKeyword = new Map();
  for (const g of gestures) {
    for (const k of [g.gloss.toLowerCase(), ...g.keywords.map(([k]) => k.toLowerCase())]) {
      if (!byKeyword.has(k)) byKeyword.set(k, g);
    }
  }
  // Grammar words (modals, "there") are carried by ASL grammar, not signed word-for-word.
  const signable = (w) => !GRAMMAR_WORDS.has(w);
  const categories = Object.entries(CORE_VOCABULARY).map(([name, words]) => {
    const ws = words.filter(signable);
    const missing = ws.filter((w) => !byKeyword.has(w));
    return { name, total: ws.length, covered: ws.length - missing.length, missing };
  });
  const grammar = [...new Set(Object.values(CORE_VOCABULARY).flat())].filter((w) => !signable(w));
  const all = [...new Set(Object.values(CORE_VOCABULARY).flat())].filter(signable);
  const missing = all.filter((w) => !byKeyword.has(w));
  const bySource = {};
  for (const w of all) { const g = byKeyword.get(w); if (g) bySource[g.source] = (bySource[g.source] || 0) + 1; }
  return { categories, total: all.length, covered: all.length - missing.length, missing, bySource, grammar };
}

export function buildReport() {
  const g = data.gestures;
  const count = (f) => g.filter(f).length;
  const bySource = { curated: count((x) => x.source === 'curated'), 'asl-lex': count((x) => x.source === 'asl-lex'), authored: count((x) => x.source === 'authored') };
  const { checked, mismatches } = crossVerify();
  const problems = validateSeed();
  const rows = new Map(loadAslLexRows().map((r) => [r.Code, r]));
  const fromLex = g.filter((x) => rows.has(x.sourceRef));
  const lexOf = (x) => rows.get(x.sourceRef);
  const nondomRestored = fromLex.filter((x) => /^(B|curved_b|Lax)$/.test(lexOf(x)['NonDominantHandshape.2.0'] || '') && x.signForm[0].H.left).length;
  const travels = g.filter((x) => x.signForm[1]?.L).length;
  const shapeChanges = g.filter((x) => x.signForm[1]?.H?.right).length;
  const extraMeanings = g.filter((x) => / \((noun|verb|adjective|adverb|number|name|other sense)\)$/.test(x.gloss)).length;
  const cov = coverage();
  const pct = (a, b) => `${Math.round((a / b) * 1000) / 10}%`;
  const reasons = {};
  for (const s of data.aslLexSkipped) (reasons[s.reason] ||= []).push(s.word);
  const uncoded = g.filter((x) => x.nondominantUncoded);
  const authored = g.filter((x) => x.source === 'authored');

  return `# SignSense vocabulary report

Generated by \`npm run seed:report -w server\` from the shipped seed data. Every number
describing the current data is computed from it, not typed.

## Summary

| | |
|---|---|
| Signs | **${g.length}** |
| From ASL-LEX 2.0 (published lexical database of ASL) | ${bySource['asl-lex']} |
| Curated core signs (phonology built from their ASL-LEX entry) | ${bySource.curated} |
| Authored for SignSense (not in ASL-LEX; needs review) | ${bySource.authored} |
| Placeholder / invented signs | **0** |
| Cross-verified against the ASL-LEX source row | ${checked} of ${g.length} (${mismatches.length} mismatches) |
| Validation problems | ${problems.length} |
| Reviewed by a fluent signer | 0 — every row keeps \`needs_review = true\` |

**What "cross-verified" means.** For every curated and ASL-LEX sign, the stored handshape(s),
sign type (which hands, same or different shape), movement shape and repetition, start and
end location, and handshape change are re-derived from that sign's ASL-LEX 2.0 row (by its
unique sign code) and must match exactly. This proves the app's data says what the published
coding says. It does **not** prove the rendering is fluent ASL: ASL-LEX does not code movement
direction, palm orientation or facial grammar, so those are approximated (see *Known limits*).

## What changed in this version

- **Removed the 360 placeholder signs of the previous version.** Their handshape, location and movement were picked by a
  hash of the English spelling — not signs at all (e.g. PHONE, POLICE, STORE, AFRAID). Words
  that ASL-LEX does sign under another English word now map there (see *same-sign synonyms*);
  the rest are left unsigned rather than shown wrong.
- **Corrected the 16 core signs** against ASL-LEX. Several were wrong: YES (two open palms →
  nodding S-fist), NO (flat-hand shake → index+middle snapping to thumb), PLEASE (two hands →
  one), WANT (one claw hand → both 5-hands), MORE (one open hand → both O-hands tapping),
  HELLO and GOOD (spread hand → flat B moving away from forehead / chin), WATER (circling →
  tapping the chin).
- **Restored the base hand in ${nondomRestored} two-handed signs.** ASL-LEX codes the non-dominant hand
  with its own labels ("B", "curved_b", "Lax"), which were not mapped, so e.g. HELP showed
  the fist without the palm it rests on.
- **${travels} signs now travel to their end location** (THANK YOU leaves the mouth, HELLO leaves
  the forehead) instead of an arbitrary upward stroke.
- **${shapeChanges} signs now show their handshape change** (the hand opening or closing mid-sign).
- **${extraMeanings} additional meanings** that share an English word are now separate signs (FALL the
  season vs FALL the verb, RIGHT as "correct" vs "a right"); before, one sign silently stood
  for both. The most familiar meaning (by ASL-LEX sign frequency) owns the bare word.
- **Real signs that were blocked are back:** WHERE, BATHROOM, SANDWICH (previously withheld
  only for tests), DRINK, THIRSTY, HUNGRY, NEED, FINE, NICE, GREAT, BREAKFAST, LUNCH, DINNER —
  these had been claimed as "synonyms" of WATER, EAT, WANT and GOOD although ASL signs them
  differently.
- **Part of speech** now comes from ASL-LEX's lexical class (was empty for every import),
  improving the English sentences built from signs.

## Everyday vocabulary coverage

${cov.covered} of ${cov.total} core everyday words (${pct(cov.covered, cov.total)}) have a sign
(${Object.entries(cov.bySource).map(([k, v]) => `${v} ${k}`).join(', ')}).

| Area | Covered | Missing |
|---|---|---|
${cov.categories.map((c) => `| ${c.name} | ${c.covered}/${c.total} | ${c.missing.join(', ') || '—'} |`).join('\n')}

Not counted: ${cov.grammar.join(', ')} — English grammar words that ASL expresses through
grammar (word order, time signs, pointing) rather than a word-for-word sign.

Missing words are never given an invented sign. In conversation, names, places and numbers
are fingerspelled; any other unsigned word is shown to both people as "no sign available".

## Authored signs (${authored.length})

Very common words that ASL-LEX does not contain, written from standard ASL dictionary
descriptions in ASL-LEX's own categories. Treat as drafts until a fluent signer checks them.

${authored.map((x) => `- **${x.gloss}**: ${x.meaning.split(' Authored')[0]}`).join('\n')}

## Known limits (approximations)

- **Movement direction.** ASL-LEX codes movement *shape* (straight, curved, circular, …) and
  repetition, not direction. Signs that travel between two coded locations move correctly;
  for the rest the avatar uses a fixed small stroke in the coded shape.
- **Palm orientation** is not coded; palms face the viewer.
- **Facial grammar.** Citation forms use a neutral face; sentence-level grammar (questions,
  negation) is layered on by the app. Lexical facial components are not represented.
- **Variants.** Where ASL-LEX records several variants of one meaning, the most familiar one
  (highest sign frequency) is used; the others are counted in the sign's description.
- **${uncoded.length} two-handed signs** have a non-dominant handshape that ASL-LEX marks only as a
  "violation" without naming it; the base hand is left out rather than guessed:
  ${uncoded.map((x) => x.gloss).join(', ')}.
- **Language.** All data is American Sign Language (ASL). No other sign language is mixed in.

## ASL-LEX meanings not imported (${data.aslLexSkipped.length})

${Object.entries(reasons).map(([r, ws]) => `- *${r}* (${ws.length}): ${ws.join(', ')}`).join('\n')}

## Source and licence

ASL-LEX 2.0 — Caselli, Sehyr, Cohen-Goldberg & Emmorey (2017), *Behavior Research Methods*
49(2); https://asl-lex.org — CC BY-NC 4.0 (non-commercial use only). See
\`server/src/db/seedData/aslLex/ATTRIBUTION.md\`.
`;
}

const isMain = process.argv[1] && process.argv[1].endsWith('vocabularyReport.js');
if (isMain) {
  const out = path.join(here, 'VOCABULARY_REPORT.md');
  fs.writeFileSync(out, buildReport());
  console.log(`Wrote ${out}`);
}
